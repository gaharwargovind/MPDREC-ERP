export const generateSubjectsSem7 = (basePerf: number): SubjectMark[] => {
  const meta = [
    { code: 'KCS-701', name: 'Artificial Intelligence & Machine Learning', credits: 4 },
    { code: 'KCS-702', name: 'Cloud Computing & Distributed Systems', credits: 4 },
    { code: 'KCS-071', name: 'Cryptography & Information Security', credits: 3 },
    { code: 'KOE-074', name: 'Renewable Energy Resources', credits: 3 },
    { code: 'KCS-751', name: 'AI & Machine Learning Lab', credits: 2 },
    { code: 'KCS-752', name: 'Major Project Phase-I', credits: 4 },
  ];

  return meta.map((sub, idx) => {
    const variation = ((idx * 5) % 11) - 4;
    const factor = Math.min(94, Math.max(56, basePerf + variation));
    const ct1 = Math.round((factor / 100) * 30 * 0.92);
    const ct2 = Math.round((factor / 100) * 30 * 0.94);
    const assignment = Math.round((factor / 100) * 20 * 0.96);
    const endSem = Math.round((factor / 100) * 100 * 0.9);

    const internalTotal = Math.min(50, Math.round(((ct1 + ct2) / 60) * 30 + assignment));
    const endSemScaled = Math.min(50, Math.round((endSem / 100) * 50));
    const total = Math.min(100, internalTotal + endSemScaled);

    let grade: SubjectMark['grade'] = 'A';
    let gradePoint = 9;
    if (total >= 90) { grade = 'A+'; gradePoint = 10; }
    else if (total >= 80) { grade = 'A'; gradePoint = 9; }
    else if (total >= 70) { grade = 'B+'; gradePoint = 8; }
    else if (total >= 60) { grade = 'B'; gradePoint = 7; }
    else if (total >= 50) { grade = 'C+'; gradePoint = 6; }
    else if (total >= 40) { grade = 'C'; gradePoint = 5; }
    else { grade = 'F'; gradePoint = 0; }

    return {
      code: sub.code,
      name: sub.name,
      credits: sub.credits,
      classTest1: ct1,
      classTest2: ct2,
      assignment,
      endSem,
      total,
      grade,
      gradePoint,
    };
  });
};

